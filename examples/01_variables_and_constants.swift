// TinySwift Example: Variables and Constants
// Demonstrates let (immutable) and var (mutable) declarations with type annotations.

// --- Immutable constants with `let` ---

let name: String = "TinySwift"
let year: Int = 2025
let pi: Double = 3.14159265358979323846
let isAwesome: Bool = true

// --- Mutable variables with `var` ---

var counter: Int = 0
var message: String = "Hello"
var temperature: Double = 72.5
var isRunning: Bool = false

// --- Multiple declarations ---

var x: Int = 0, y: Int = 1, z: Int = 2

// --- Reassignment (only allowed for `var`) ---

counter = counter + 1
message = "World"
temperature = 68.0
isRunning = true

// --- Using constants in expressions ---

let circumference: Double = 2.0 * pi * 10.0
let greeting: String = "Welcome to TinySwift"

// --- Type-annotated declarations ---

let maxSize: Int = 1024
let epsilon: Double = 0.000001
let delimiter: String = ", "
let verbose: Bool = false
